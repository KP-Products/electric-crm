export const useCheckAction = () => {
  const actionList = useSelector(selectActions);
  const hasPermission = (action: string) => {
    if (!actionList || actionList.length === 0 || !action) return false;
    return actionList.includes(action);
  };
  return { actionList, hasPermission };
};
